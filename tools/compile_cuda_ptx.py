import ctypes, os

torch_lib = r'C:\Users\AFFAN\AppData\Roaming\Python\Python311\site-packages\torch\lib'
os.environ["PATH"] = torch_lib + os.pathsep + os.environ["PATH"]
os.add_dll_directory(torch_lib)
nvrtc = ctypes.windll.LoadLibrary(os.path.join(torch_lib, 'nvrtc64_120_0.dll'))

with open(r'D:\affan_ai_engine_2_mini\engine_cpp\affa_kernels.cu', 'rb') as f:
    cu_src = f.read()

prog = ctypes.c_void_p()
res = nvrtc.nvrtcCreateProgram(ctypes.byref(prog), cu_src, b'affa_kernels.cu', 0, None, None)

opts = [b'--gpu-architecture=compute_75', b'--std=c++17']
c_opts = (ctypes.c_char_p * len(opts))(*opts)
cres = nvrtc.nvrtcCompileProgram(prog, len(opts), c_opts)
print('cres:', cres)

log_size = ctypes.c_size_t()
nvrtc.nvrtcGetProgramLogSize(prog, ctypes.byref(log_size))
log = ctypes.create_string_buffer(log_size.value)
nvrtc.nvrtcGetProgramLog(prog, log)
if log.value:
    print('Log:', log.value.decode('utf-8', errors='ignore'))

if cres == 0:
    ptx_size = ctypes.c_size_t()
    nvrtc.nvrtcGetPTXSize(prog, ctypes.byref(ptx_size))
    ptx = ctypes.create_string_buffer(ptx_size.value)
    nvrtc.nvrtcGetPTX(prog, ptx)
    ptx_bytes = ptx.raw[:ptx_size.value]
    
    # Verify loading on RTX 5050
    cuda = ctypes.windll.LoadLibrary('nvcuda.dll')
    cuda.cuInit(0)
    dev = ctypes.c_int()
    cuda.cuDeviceGet(ctypes.byref(dev), 0)
    ctx = ctypes.c_void_p()
    cuda.cuCtxCreate_v2(ctypes.byref(ctx), 0, dev.value)

    module = ctypes.c_void_p()
    lres = cuda.cuModuleLoadData(ctypes.byref(module), ptx_bytes)
    print('cuModuleLoadData on RTX 5050 result =', lres)
    
    # Check all kernel functions
    for k in [b'k_embed', b'k_norm_quant', b'k_matmul_1', b'k_qkv_1', b'k_gu_1', b'k_matmul_8', b'k_add', b'k_qk_rope', b'k_attn', b'k_logits', b'k_topk_256']:
        fn = ctypes.c_void_p()
        fres = cuda.cuModuleGetFunction(ctypes.byref(fn), module, k)
        print(f'Kernel {k.decode()} function pointer =', fn.value, 'res =', fres)
        
    # Write C header
    with open(r'D:\affan_ai_engine_2_mini\engine_cpp\affa_ptx.h', 'w', encoding='utf-8') as hf:
        hf.write('#pragma once\n// Autogenerated PTX for RTX 5050 / Blackwell / Ada\n')
        hf.write('const char kAffaPtx[] =\n')
        lines = ptx_bytes.decode('utf-8', errors='ignore').splitlines()
        for line in lines:
            escaped = line.replace('\\', '\\\\').replace('"', '\\"')
            hf.write(f'  "{escaped}\\n"\n')
        hf.write(';\n')
        hf.write(f'const unsigned int kAffaPtxLen = {len(ptx_bytes)};\n')
        
    print('SUCCESS! Wrote D:\\affan_ai_engine_2_mini\\engine_cpp\\affa_ptx.h (size:', len(ptx_bytes), 'bytes)')
